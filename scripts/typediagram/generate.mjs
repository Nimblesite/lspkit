#!/usr/bin/env node
// Implements [PROF-WIRE-GEN].
//
// Regenerates the wire models of the lsp-profiler protocol from the single
// source of truth, docs/models/profiler.td (+ profiler-methods.json):
//   crates/lsp-profiler/src/wire_generated.rs
//   packages/lsp-profiler-ui/src/wire-generated.ts
// Both outputs are gitignored. `crates/lsp-profiler/build.rs` and the UI
// package's `prebuild` script run this file, so a fresh checkout always
// builds against the current model.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { decorateRust, rustConstants } from "./rust-emit.mjs";
import { captureStdout } from "./run-cli.mjs";
import { extractDocs } from "./td-docs.mjs";
import { decorateTs, tsConstants } from "./ts-emit.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const TD_PATH = resolve(ROOT, "docs/models/profiler.td");
const METHODS_PATH = resolve(ROOT, "docs/models/profiler-methods.json");
const OUT_RUST = resolve(ROOT, "crates/lsp-profiler/src/wire_generated.rs");
const OUT_TS = resolve(ROOT, "packages/lsp-profiler-ui/src/wire-generated.ts");

const RUST_HEADER = `// @generated by scripts/typediagram/generate.mjs from docs/models/profiler.td.
// DO NOT EDIT BY HAND — edit the .td model and rebuild. This file is gitignored.
`;
const TS_HEADER = `// @generated by scripts/typediagram/generate.mjs from docs/models/profiler.td.
// DO NOT EDIT BY HAND — edit the .td model and rebuild. This file is gitignored.
`;

function typediagram(target) {
  return captureStdout("typediagram", ["--to", target, TD_PATH]);
}

// Rewriting identical content would bump the mtime and force cargo to rebuild
// every dependent crate, so the file is only written when it changes.
function writeIfChanged(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  try {
    if (readFileSync(path, "utf8") === contents) return "unchanged";
  } catch {
    // Missing file: fall through and write it.
  }
  writeFileSync(path, contents, "utf8");
  return "wrote";
}

function main() {
  const docs = extractDocs(readFileSync(TD_PATH, "utf8"));
  const table = JSON.parse(readFileSync(METHODS_PATH, "utf8"));
  const rust = `${RUST_HEADER}\n${decorateRust(typediagram("rust"), docs)}\n${rustConstants(table)}\n`;
  const ts = `${TS_HEADER}\n${decorateTs(typediagram("typescript"), docs)}\n${tsConstants(table)}\n`;
  process.stdout.write(`typediagram-gen: ${writeIfChanged(OUT_RUST, rust)} ${OUT_RUST}\n`);
  process.stdout.write(`typediagram-gen: ${writeIfChanged(OUT_TS, ts)} ${OUT_TS}\n`);
}

main();
